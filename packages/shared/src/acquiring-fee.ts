/**
 * Комиссия эквайринга, удержанная банком внутри строки возмещения.
 *
 * Альфа зачисляет торговое возмещение уже за вычетом своей комиссии — одной
 * строкой на нетто-сумму, а удержанное пишет прямо в назначении:
 *
 *   `Возм 667302152487 17.10.2025 ИП КАМЕНСКИЙ ИЛЬЯ ЮРЬЕ Р.09072026 К.4837.50 в т.ч. НДС 872.34`
 *                                                                    ↑ комиссия
 *
 * Без разбора такая строка ломает две вещи сразу: заказ выглядит недоплаченным
 * ровно на комиссию, а расход банка нигде не виден. Поэтому при привязке к
 * заказу строка расщепляется на оплату (брутто = зачислено + комиссия) и
 * расход «Банковские услуги» — сальдо по счёту остаётся равным тому, что
 * реально пришло от банка.
 *
 * Формат намеренно узкий: требуем и маркер `Возм`, и дату расчёта `Р.ДДММГГГГ`
 * перед суммой. Иначе любое `К.` в свободном тексте назначения (например, в
 * номере договора) превратилось бы в фантомный расход.
 */
// `\b` здесь бесполезен: в JS граница слова знает только ASCII, а «Возм» —
// кириллица, поэтому маркер ищем как есть.
const ACQUIRING_FEE = /Возм[\s\S]{0,140}?Р\.\d{8}\s+К\.(\d+(?:[.,]\d{1,2})?)/u;

/**
 * Возвращает удержанную комиссию как Decimal-строку либо null, если строка не
 * похожа на торговое возмещение с удержанием.
 */
export function parseAcquiringFee(description: string | null | undefined): string | null {
  if (!description) return null;
  const match = ACQUIRING_FEE.exec(description);
  if (!match?.[1]) return null;
  const fee = match[1].replace(',', '.');
  // «К.0» встречается на возмещениях без удержания — расщеплять нечего.
  return Number(fee) > 0 ? fee : null;
}
