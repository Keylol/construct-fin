-- Ревизия авто-проведённого: какое правило превратило строку выписки в проводку.
--
-- Сработавшее правило создаёт проводку сразу, без подтверждения человеком. Пока
-- строка не помнит, КАКОЕ правило её провело, ошибку одного правила невозможно ни
-- найти, ни откатить пачкой — а на перезаливе истории это сотни проводок.
--
-- Без FK на Rule — как и suggestedCategoryId рядом: правило удаляется мягко
-- (deletedAt), а ссылка нужна историческая и должна пережить удаление правила.
--
-- Миграция написана вручную (не через `migrate dev`), чтобы не тянуть в неё
-- DROP INDEX для partial-unique индексов — см. «Известные грабли» в CLAUDE.md.
ALTER TABLE "BankStatementLine" ADD COLUMN "appliedRuleId" TEXT;

-- Массовый откат «всё, что провело правило X» и счётчик срабатываний правила.
CREATE INDEX "BankStatementLine_workspaceId_appliedRuleId_idx"
  ON "BankStatementLine"("workspaceId", "appliedRuleId");
