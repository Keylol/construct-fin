-- Телефон клиента как видимый номер заказа.
--
-- В спецификациях («Заказ №: +7 924 363 40 29») номером всегда служит телефон,
-- и владелец опознаёт заказы именно по нему. Внутренний «ORD-2026-0041»
-- остаётся: на него ссылаются описания проводок и partial-unique индекс, а
-- телефон уникальным быть не может — у повторного клиента несколько заказов с
-- одним номером, они группируются в списке.
--
-- Колонка nullable: у 41 заказа, заведённого до этого решения, телефона нет —
-- он проставляется бэкфиллом из архивов. Для новых заказов поле обязательно на
-- уровне DTO.
--
-- Миграция написана вручную (не через `migrate dev`), чтобы не тянуть в неё
-- DROP INDEX для partial-unique индексов — см. «Известные грабли» в CLAUDE.md.
ALTER TABLE "Order" ADD COLUMN "phone" TEXT;

-- Поиск заказа по телефону и группировка заказов одного клиента.
CREATE INDEX "Order_workspaceId_phone_idx" ON "Order"("workspaceId", "phone");
