import type { TransactionKind } from '@prisma/client';

/**
 * Классификация kind'ов для расчётов денег vs прибыли (правила R1/R2).
 *
 * Деньги (остаток счёта, денежный поток, сверка, дашбордный «net денег»)
 * считаются ТОЛЬКО по реальным движениям средств.
 */

/**
 * Ноги перевода между своими счетами. В КОНСОЛИДИРОВАННЫХ расчётах (пул всех
 * счетов, дашборд) гасят друг друга → исключаются. В расчётах ПО ОДНОМУ счёту
 * (сверка, cashflow byAccount) — это реальное движение средств этого счёта,
 * поэтому НЕ исключаются. Комиссия перевода (VARIABLE_COST) — всегда реальный
 * расход, в этот список НЕ входит.
 */
export const TRANSFER_LEG_KINDS: TransactionKind[] = ['TRANSFER_IN', 'TRANSFER_OUT'];

/**
 * Неденежные kind: бухгалтерская проводка, реальные деньги НЕ двигались.
 * COGS (cash-basis, R1) признаётся при продаже только для отчёта о прибыли и
 * маржи — деньги за товар ушли в момент закупки. Поэтому COGS НЕ должен влиять
 * на остаток счёта / денежный поток / сверку (R2). Исключается во ВСЕХ денежных
 * расчётах, но ОСТАЁТСЯ в P&L (там это легитимная себестоимость услуг).
 */
export const NON_CASH_KINDS: TransactionKind[] = ['COGS'];

/** Исключаются из денежного расчёта по ОДНОМУ счёту (переводы — реальны для счёта). */
export const NON_CASH_FOR_ACCOUNT: TransactionKind[] = [...NON_CASH_KINDS];

/** Исключаются из КОНСОЛИДИРОВАННОГО денежного расчёта (пул счетов / дашборд). */
export const NON_CASH_CONSOLIDATED: TransactionKind[] = [...TRANSFER_LEG_KINDS, ...NON_CASH_KINDS];
