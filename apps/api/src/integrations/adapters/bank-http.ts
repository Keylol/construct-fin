/**
 * Общий HTTP-контракт банковских адаптеров (Ф2/Ф3).
 *
 * Адаптеры зависят от этого интерфейса, а не от конкретного транспорта:
 * у Альфы транспорт с клиентским сертификатом mTLS (`node:https`), у Т-Банка —
 * обычный fetch с Bearer-токеном. Тест подставляет объект без сети.
 *
 * Тело ответа отдаётся строкой: разбор и валидация — забота адаптера, который
 * знает формат своего банка (и его формат ошибок).
 */
export interface BankHttpResponse {
  status: number;
  body: string;
  headers: Record<string, string | string[] | undefined>;
}

export interface BankHttp {
  /** Настроен ли транспорт (Альфе нужен сертификат; Т-Банку — ничего). */
  readonly configured: boolean;
  getJson(url: string, headers: Record<string, string>): Promise<BankHttpResponse>;
}

/**
 * Секрет подключения уходит в заголовок Authorization, а заголовки — это
 * latin1: токен с кириллицей или переводом строки роняет HTTP-клиент технической
 * ошибкой вида «Cannot convert argument to a ByteString», которая доезжает до
 * владельца как непонятный текст в статусе подключения.
 *
 * Случай не выдуманный: токен копируют из письма или личного кабинета, вместе с
 * ним легко утащить пробел, перевод строки или кириллическую букву-двойника.
 * Проверяем до запроса и говорим по-человечески. Сам токен в сообщение,
 * разумеется, не попадает.
 */
export function assertHeaderSafe(token: string): void {
  // Печатные ASCII без пробела: всё, что банки используют в ключах и токенах.
  if (!/^[\x21-\x7e]+$/.test(token)) {
    throw new Error(
      'Ключ доступа содержит недопустимые символы (пробел, перенос строки или кириллицу) — скопируйте его из банка целиком и вставьте заново',
    );
  }
}
