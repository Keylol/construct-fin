import { describe, it, expect } from 'vitest';
import { parseAcquiringFee } from '@construct/shared';

describe('комиссия эквайринга, удержанная внутри строки возмещения', () => {
  it('берёт сумму после «К.» в торговом возмещении', () => {
    expect(
      parseAcquiringFee(
        'Возм 667302152487 17.10.2025 ИП КАМЕНСКИЙ ИЛЬЯ ЮРЬЕ Р.09072026 К.4837.50 в т.ч. НДС 872.34',
      ),
    ).toBe('4837.50');
  });

  it('целое число без копеек', () => {
    expect(
      parseAcquiringFee('Возм 667302152487 17.10.2025 ИП КАМЕНСКИЙ Р.29072026 К.11299 в т.ч. НДС 2037.58'),
    ).toBe('11299');
  });

  it('запятая как разделитель', () => {
    expect(parseAcquiringFee('Возм 667302152487 Р.25062026 К.2073,18 в т.ч. НДС 373.85')).toBe('2073.18');
  });

  // СБП присылает комиссию отдельной строкой «Комиссия к возм. по дог.№ …» с тем же
  // идентификатором, что и приход. Расщепить такое возмещение — значит учесть
  // комиссию дважды.
  it('возмещение по СБП не трогаем — там комиссия отдельной строкой', () => {
    expect(
      parseAcquiringFee(
        'C302407260716138 Возм. по согл. в СБП № 667302152487 от RB ПК CONSTRUCTPC (AMD Ryzen 7 7800X3D; RTX 5070)',
      ),
    ).toBeNull();
  });

  it('нулевое удержание — расщеплять нечего', () => {
    expect(parseAcquiringFee('Возм 667302152487 Р.01072026 К.0 в т.ч. НДС 0')).toBeNull();
  });

  // Требуем и маркер возмещения, и дату расчёта перед суммой: иначе «К.» из
  // произвольного назначения (номер договора, инициалы) дало бы фантомный расход.
  it('«К.» в постороннем назначении не считается комиссией', () => {
    expect(parseAcquiringFee('Оплата по счёту К.4837.50 от ООО Ромашка')).toBeNull();
    expect(parseAcquiringFee('Перевод средств Р.09072026 К.100 без маркера возмещения')).toBeNull();
  });

  it('пустое назначение', () => {
    expect(parseAcquiringFee(null)).toBeNull();
    expect(parseAcquiringFee('')).toBeNull();
  });
});
